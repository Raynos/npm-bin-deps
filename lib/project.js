'use strict'

// The project: its package.json, its binDependencies, and the files npr
// generates into binDependenciesDir.

const fs = require('node:fs')
const path = require('node:path')

const { UserError } = require('./log.js')

const DEFAULT_DIR = '.bin-deps'
const GENERATED_NAME = 'bin-dependencies'

/**
 * @typedef {{
 *   root: string,
 *   packageJSONFile: string,
 *   pkg: Record<string, any>,
 *   binDependencies: Record<string, string> | undefined,
 *   dir: string
 * }} Project
 */

/**
 * Read the package.json in `root`.
 *
 * @param {string} root
 * @returns {Project}
 */
function readProject (root) {
  const packageJSONFile = path.join(root, 'package.json')
  /** @type {Record<string, any>} */
  let pkg
  try {
    pkg = JSON.parse(fs.readFileSync(packageJSONFile, 'utf8'))
  } catch (err) {
    throw new UserError('Could not read your application package.json', [
      `Expected valid package.json at ${packageJSONFile}`,
      String(/** @type {Error} */ (err).message)
    ])
  }
  if (!pkg || typeof pkg !== 'object' || Array.isArray(pkg)) {
    throw new UserError(`Expected a JSON object in ${packageJSONFile}`)
  }

  const deps = pkg.binDependencies
  if (deps !== undefined && (typeof deps !== 'object' || deps === null || Array.isArray(deps))) {
    throw new UserError('"binDependencies" in package.json must be an object')
  }

  const dirField = pkg.binDependenciesDir
  if (dirField !== undefined && (typeof dirField !== 'string' || dirField === '')) {
    throw new UserError('"binDependenciesDir" in package.json must be a non-empty string')
  }

  return {
    root,
    packageJSONFile,
    pkg,
    binDependencies: deps,
    dir: path.resolve(root, dirField || DEFAULT_DIR)
  }
}

/**
 * The project npr uses from `cwd`: the nearest package.json, at or above
 * `cwd`, that has binDependencies, so a workspace package uses the bin
 * deps of its monorepo root. With none, the package.json in `cwd`.
 *
 * @param {string} cwd
 * @returns {Project}
 */
function findProject (cwd) {
  let dir = path.resolve(cwd)
  for (;;) {
    if (fs.existsSync(path.join(dir, 'package.json'))) {
      const project = readProject(dir)
      if (project.binDependencies) return project
    }
    const parent = path.dirname(dir)
    if (parent === dir) return readProject(cwd)
    dir = parent
  }
}

/**
 * Save new binDependencies into the project's package.json.
 *
 * @param {Project} project
 * @param {Record<string, string>} deps
 */
function writeBinDependencies (project, deps) {
  project.pkg.binDependencies = deps
  project.binDependencies = deps
  fs.writeFileSync(
    project.packageJSONFile,
    JSON.stringify(project.pkg, null, 2) + '\n',
    'utf8'
  )
}

/**
 * Sort an object's keys.
 *
 * @param {Record<string, string>} obj
 * @returns {Record<string, string>}
 */
function sortKeys (obj) {
  /** @type {Record<string, string>} */
  const out = {}
  for (const key of Object.keys(obj).sort()) out[key] = obj[key]
  return out
}

/**
 * The package.json npr writes into binDependenciesDir: the project's
 * binDependencies as plain dependencies, plus the project's overrides
 * in the field the manager reads (`overrides` for npm,
 * `"pnpm".overrides` for pnpm).
 *
 * @param {Record<string, string>} deps
 * @param {{
 *   manager?: 'npm' | 'pnpm',
 *   overrides?: import('./config.js').Overrides | null
 * }} [extra]
 * @returns {string}
 */
function generatedPackageJSON (deps, extra) {
  /** @type {Record<string, unknown>} */
  const pkg = {
    name: GENERATED_NAME,
    private: true,
    description: 'Generated by npm-bin-deps from "binDependencies" in ' +
      'the project package.json. Do not edit; run npr install.',
    dependencies: sortKeys(deps)
  }
  const overrides = extra && extra.overrides
  if (extra && overrides) {
    if (extra.manager === 'pnpm') pkg.pnpm = { overrides }
    else pkg.overrides = overrides
  }
  return JSON.stringify(pkg, null, 2) + '\n'
}

module.exports = {
  DEFAULT_DIR,
  readProject,
  findProject,
  writeBinDependencies,
  generatedPackageJSON
}
